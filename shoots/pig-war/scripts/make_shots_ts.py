#!/usr/bin/env python3
"""Generate the short cut's timeline from the assembled narration.

Reads shoots/pig-war/voice/words.json and emits:
  remotion-app/src/videos/pig-war/shots.ts    — shot boundaries (frames) + captions (seconds)
Every cut lands on the word that opens its sentence, so the picture changes when the line does.

    python3 shoots/pig-war/scripts/make_shots_ts.py
"""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
WORDS = os.path.join(ROOT, "shoots/pig-war/voice/words.json")
OUT = os.path.join(ROOT, "remotion-app/src/videos/pig-war/shots.ts")
FPS = 30
TOTAL = 3070  # 102.3 s: narration is 100.55 s, then the last image holds into the music tail

# (sentence-opening words, set, light) — the short cut's picture plan
PLAN = [
    ("One pig started", "patch", "golden"),
    ("San Juan Island", "strait", "day"),
    ("In 1846", "chart", "day"),
    ("There are two channels", "chart", "day"),
    ("So for thirteen", "strait", "day"),
    ("Britain got there", "bellevue", "day"),
    ("Six years later", "farm", "day"),
    ("Americans came anyway", "prairie", "day"),
    ("Then, on the", "patch", "golden"),
    ("Cutlar had already", "fence", "day"),
    ("This time he", "patch", "day"),
    ("Griffin wanted a", "fence", "day"),
    ("Cutlar offered ten", "fence", "day"),
    ("Britain threatened to", "porch", "day"),
    ("So the settlers", "porch", "day"),
    ("America sent sixty-four", "camp", "day"),
    ("Britain sent five", "strait", "day"),
    ("The two sides", "between", "day"),
    ("They didn't", "between", "day"),
    ("For twelve years", "camp", "golden"),
    ("In 1872", "chart", "golden"),
    ("Nobody died in", "garden", "golden"),
    ("The garden is", "garden", "golden"),
]

with open(WORDS) as f:
    words = json.load(f)


def norm(s: str) -> str:
    return re.sub(r"[^a-z0-9']", "", s.lower())


flat = [norm(w["word"]) for w in words]


def find(prefix: str, start: int) -> int:
    want = [norm(p) for p in prefix.split()]
    for i in range(start, len(flat) - len(want) + 1):
        if flat[i:i + len(want)] == want:
            return i
    raise SystemExit(f"not found after {start}: {prefix!r}")


rows = []
i = 0
for prefix, set_id, light in PLAN:
    idx = find(prefix, i)
    i = idx
    rows.append((words[idx]["start"], set_id, light, idx))

shots = []
for k, (t, set_id, light, idx) in enumerate(rows):
    a = max(0, round(t * FPS) - 2) if k else 0
    b = round(rows[k + 1][0] * FPS) - 2 if k + 1 < len(rows) else TOTAL
    shots.append((a, b, set_id, light, idx))

# ---- captions: 1-2 words a card, never across a sentence break ----
STOP = {"the", "a", "an", "of", "to", "in", "and", "or", "it", "at", "on", "for", "was", "were", "is",
        "that", "this", "they", "he", "she", "his", "her", "their", "had", "has", "have", "with", "as", "by"}
cards = []
k = 0
while k < len(words):
    w = words[k]
    text = w["word"]
    b = w["end"]
    nxt = words[k + 1] if k + 1 < len(words) else None
    # glue a short/stop word to the next one when they are in the same breath
    if nxt and len(text) <= 4 and (norm(text) in STOP or len(text) <= 3) and nxt["start"] - w["end"] < 0.30:
        text = f"{text} {nxt['word']}"
        b = nxt["end"]
        k += 1
    cards.append((max(0.0, w["start"] - 0.04), b + 0.06, text))
    k += 1

lines = [
    "// generated by shoots/pig-war/scripts/make_shots_ts.py — do not edit",
    f"export const TOTAL_FRAMES = {TOTAL};",
    "export type ShotRow = { a: number; b: number; set: string; light: \"day\" | \"golden\"; word: number };",
    "export const SHOT_ROWS: ShotRow[] = [",
]
for a, b, set_id, light, idx in shots:
    lines.append(f'  {{ a: {a}, b: {b}, set: "{set_id}", light: "{light}", word: {idx} }},')
lines.append("];")
lines.append("export type Card = { a: number; b: number; text: string };")
lines.append("export const CARDS: Card[] = [")
for a, b, text in cards:
    lines.append(f'  {{ a: {a:.3f}, b: {b:.3f}, text: {json.dumps(text)} }},')
lines.append("];")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")

print(f"{len(shots)} shots, {len(cards)} caption cards -> {os.path.relpath(OUT, ROOT)}")
for a, b, set_id, _, _ in shots:
    print(f"  {a / FPS:6.2f}s - {b / FPS:6.2f}s  {set_id}")
