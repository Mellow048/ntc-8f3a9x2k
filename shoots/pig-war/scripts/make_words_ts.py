#!/usr/bin/env python3
"""Generate remotion-app/src/videos/pig-war/words.ts from shoots/pig-war/voice/words.json.

The Remotion app does not enable resolveJsonModule, so the 657-word timing table is
emitted as a plain TS literal (one line per 20 words keeps the diff readable).

    python3 shoots/pig-war/scripts/make_words_ts.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SRC = os.path.join(ROOT, "shoots/pig-war/voice/words.json")
OUT = os.path.join(ROOT, "remotion-app/src/videos/pig-war/words.ts")

with open(SRC) as f:
    words = json.load(f)

lines = [
    "// generated by shoots/pig-war/scripts/make_words_ts.py from shoots/pig-war/voice/words.json — do not edit",
    f"// {len(words)} words; times in seconds from the assembled narration.",
    "export const WORD_TEXT: string[] = [",
]
for i in range(0, len(words), 12):
    chunk = words[i:i + 12]
    lines.append("  " + " ".join(f"{json.dumps(w['word'])}," for w in chunk))
lines.append("];")
lines.append("export const WORD_T: [number, number][] = [")
for i in range(0, len(words), 8):
    chunk = words[i:i + 8]
    lines.append("  " + " ".join(f"[{w['start']:.3f}, {w['end']:.3f}]," for w in chunk))
lines.append("];")

with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(words)} words -> {os.path.relpath(OUT, ROOT)}")
