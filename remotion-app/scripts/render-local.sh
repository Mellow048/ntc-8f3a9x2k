#!/usr/bin/env bash
# Render a news short on this machine, step for step the way .github/workflows/render-short.yml does it on GitHub's
# runners: the same `remotion render` command for every part, the same stitch, the same sound encode with its check,
# the same film check and the same two gates (true peak at most -1.0 dBFS, loudness between -17 and -13 LUFS).
#
# For when the workflow cannot be used: the session's branch can no longer be pushed to, so there is nothing for a
# runner to check out. It is slow: software WebGL on two cores does 1.6 to 4.5 s a frame at 720x1280, one to nearly
# three hours for a 75-second film. Start it with the process tool, not with a plain shell call, and wait for the line
# RENDER-LOCAL-DONE.
#
# How far it has been used (13 November 2026, on the eighth film): every step has run, the render loop on ONE part,
# in two runs with 74 parts, 73 of them cut from that film's Actions render. The first run type-checked, planned,
# bundled and rendered the one part named as its sixth argument (30 frames in 47 s; the same picture as the Actions
# file, 45.8 dB PSNR or more). The second, with every part in place, stitched 2231 frames, encoded the sound and
# checked it against the WAV, ran the film check (clean) and both gates, and wrote the MP4 and its report, in 41 s.
# A whole film has never been rendered with it, and the second and third attempt at a part have never been needed.
# Every part must come from `remotion render`: in the first run the 73 cut parts had another time base than the
# rendered one, and the stitch kept its 2231 frames and came out 288 s long.
#
#   cd remotion-app
#   scripts/render-local.sh <Composition> <mix.wav> <shots.json> <out.mp4> [parts=12] ["03 07" = parts to render again]
#   scripts/render-local.sh BtcFlexShort ../shoots/bitcoin-flex/audio/mix.wav ../shoots/bitcoin-flex/qa-shots.json \
#       ../shoots/bitcoin-flex/final-720p.mp4          (after `references/news/restore.py bitcoin-flex --mix`)
#
# Parts are kept in out/local-<Composition>/part-NN.mp4. A part that is there is not rendered again, so a run that
# died carries on where it stopped, and a new sound mix costs a minute (the picture is reused). After a change to
# the picture, name the parts it touches as the sixth argument (scripts/plan.mjs prints the frame ranges), or delete
# the folder to render everything. The film check's report is written next to the MP4 as qa-report.md.
#
# Needs: node_modules (npm ci), a browser (scripts/local-chromium.sh), ffmpeg and ffprobe on the PATH, and a Python
# with numpy and pillow (PYTHON=... to name it; default python3). The film check takes 1.2 GB of memory.
# CONCURRENCY=1 renders in one browser tab instead of two.
# Do not edit this file while it runs (the shell reads it as it goes), and stop it with care: `remotion render` and its
# browser outlive a plain stop and have to be killed by name.
set -euo pipefail
COMP=${1:?composition id}; MIX=${2:?mix.wav}; SHOTS=${3:?shots.json}; DEST=${4:?output mp4}; PARTS=${5:-12}; AGAIN=${6:-}
PY=${PYTHON:-python3}
CONC=${CONCURRENCY:-2}              # browser tabs rendering at once; 1 if the machine runs out of memory
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$REPO/remotion-app"
command -v ffmpeg >/dev/null && command -v ffprobe >/dev/null || { echo "ffmpeg and ffprobe must be on the PATH" >&2; exit 2; }
CHROME="${REMOTION_BROWSER:-$(scripts/local-chromium.sh)}"
export REMOTION_BROWSER="$CHROME"
WORK="out/local-$COMP"; mkdir -p "$WORK"
t0=$(date +%s); say() { echo "[$(( $(date +%s) - t0 )) s] $*"; }

npx tsc --noEmit -p .
say "typecheck passed"
PLAN="$(node scripts/plan.mjs "$COMP" "$PARTS")"
FRAMES="$(sed -n 's/^frames=//p' <<<"$PLAN")"
node -e 'const m = JSON.parse(process.argv[1]).include; for (const p of m) console.log(p.part, p.range);' "$(sed -n 's/^matrix=//p' <<<"$PLAN")" > "$WORK/plan.txt"
say "$COMP: $FRAMES frames in $(wc -l < "$WORK/plan.txt") parts"
for p in $AGAIN; do rm -f "$WORK/part-$p.mp4"; done

# One bundle for all parts (the workflow bundles in every job; here that would cost a quarter of an hour).
need=0; while read -r part range; do [ -s "$WORK/part-$part.mp4" ] || need=1; done < "$WORK/plan.txt"
if [ "$need" = 1 ]; then
  rm -rf "$WORK/bundle"
  npx remotion bundle src/index.ts --out-dir "$WORK/bundle" > "$WORK/bundle.log" 2>&1 || { tail -20 "$WORK/bundle.log"; exit 1; }
  say "bundled"
fi
while read -r part range; do
  out="$WORK/part-$part.mp4"
  if [ -s "$out" ]; then say "part $part ($range): kept"; continue; fi
  ok=""
  for attempt in 1 2 3; do            # a software-GL tab can die mid-render; a part is small enough to simply try again
    if npx remotion render "$WORK/bundle" "$COMP" "$WORK/tmp-$part.mp4" --codec h264 --crf 16 --width=720 --height=1280 \
        --frames="$range" --muted --gl=swiftshader --timeout=300000 --concurrency="$CONC" --browser-executable="$CHROME" > "$WORK/render-$part.log" 2>&1; then
      mv "$WORK/tmp-$part.mp4" "$out"; ok=1; break
    fi
    say "part $part ($range): attempt $attempt failed"; tail -5 "$WORK/render-$part.log"
  done
  [ -n "$ok" ] || { echo "part $part could not be rendered" >&2; exit 1; }
  say "part $part ($range): rendered"
done < "$WORK/plan.txt"

# Stitch, exactly as the workflow does.
ls "$WORK"/part-*.mp4 | sort | sed "s|^|file '$PWD/|; s|$|'|" > "$WORK/parts.txt"
ffmpeg -v error -y -f concat -safe 0 -i "$WORK/parts.txt" -c copy "$WORK/video.mp4"
GOT="$(ffprobe -v error -select_streams v:0 -count_packets -show_entries stream=nb_read_packets -of csv=p=0 "$WORK/video.mp4" | tr -dc '0-9')"
say "stitched: $GOT frames, expected $FRAMES"; test "$GOT" = "$FRAMES"

# The sound: padded or cut to the picture's exact length; the first AAC setting whose decode matches the WAV is kept.
DUR="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$WORK/video.mp4")"
OK=""
for OPTS in "-b:a 192k" "-b:a 192k -aac_coder fast" "-b:a 256k" "-b:a 192k -aac_pns 0 -aac_is 0 -aac_tns 0" "-b:a 320k"; do
  # shellcheck disable=SC2086
  ffmpeg -v error -y -i "$MIX" -af apad -t "$DUR" -c:a aac $OPTS "$WORK/audio.m4a"
  if "$PY" "$REPO/templates/scripts/aac_check.py" "$MIX" "$WORK/audio.m4a"; then OK="$OPTS"; break; fi
  say "aac $OPTS: the encode does not match the WAV; trying the next setting"
done
test -n "$OK"; say "aac setting kept: $OK"
ffmpeg -v error -y -i "$WORK/video.mp4" -i "$WORK/audio.m4a" -map 0:v:0 -map 1:a:0 -c copy -movflags +faststart "$WORK/final.mp4"
GOT="$(ffprobe -v error -select_streams v:0 -count_packets -show_entries stream=nb_read_packets -of csv=p=0 "$WORK/final.mp4" | tr -dc '0-9')"
say "with the sound on: $GOT frames, expected $FRAMES"; test "$GOT" = "$FRAMES"

# The film check and its two gates.
rm -rf "$WORK/qa"
"$PY" "$REPO/templates/scripts/short_qa.py" "$WORK/final.mp4" "$WORK/qa" "$SHOTS" > "$WORK/qa.txt"
grep -E '^(SPECS|LOUDNESS|SILENCES|FRAMES|POPS|MOTION)' "$WORK/qa.txt"
LUFS="$(grep -m1 '^LOUDNESS' "$WORK/qa.txt" | sed -E 's/.*I: +(-?[0-9.]+) LUFS.*/\1/')"
PEAK="$(grep -m1 '^LOUDNESS' "$WORK/qa.txt" | sed -E 's/.*Peak: +(-?[0-9.]+) dBFS.*/\1/')"
say "integrated loudness $LUFS LUFS (gate -17 to -13), true peak $PEAK dBFS (gate: at most -1.0)"
"$PY" -c "import sys; sys.exit(0 if -17 <= float('$LUFS') <= -13 and float('$PEAK') <= -1.0 else 1)"

mkdir -p "$(dirname "$DEST")"
cp "$WORK/final.mp4" "$DEST"; cp "$WORK/qa/report.md" "$(dirname "$DEST")/qa-report.md"
say "RENDER-LOCAL-DONE $DEST ($(stat -c %s "$DEST") bytes, sha256 $(sha256sum "$DEST" | cut -c1-16)...)"
